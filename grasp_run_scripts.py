"""从工作目录记录生成可独立运行的派生脚本，只使用标准库。"""

import errno
import os
from pathlib import Path
import re
import shlex
import stat
import uuid

import grasp_core as core
from grasp_core import T
from grasp_slurm import path_expression
import grasp_summary as summary

DIRECTORY = "grasp_run"
MARKER = "# Generated by the GRASP GUI; edits will be overwritten."
SCRIPTS = ("run.sh", "submit.sbatch")
DIR_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
# 保留 POSIX sh 保留字；这些名字不能定义为包装函数。
RESERVED = {"if", "then", "else", "elif", "fi", "do", "done", "case", "esac", "while", "until", "for", "in",
            "function", "select", "time", "!", "{", "}", "break", "continue", "eval", "exec", "exit", "export",
            "readonly", "return", "set", "shift", "times", "trap", "unset"}

RUN_SETUP = r'''integer() {
    case "$1" in ''|*[!0-9]*) return 1 ;; esac
    value=$(printf '%s' "$1" | sed 's/^0*//')
    value=${value:-0}
    [ "${#value}" -le 9 ] || return 1
    printf '%s' "$value"
}
bad_setting() {
    printf 'Invalid %s: %s (expected %s)\n' "$1" "$2" "$3" >&2
    exit 2
}
case $# in
    0) start=1; end=$step_count ;;
    2) start=$(integer "$1") || usage; end=$(integer "$2") || usage ;;
    *) usage ;;
esac
[ "$start" -ge 1 ] && [ "$start" -le "$end" ] && [ "$end" -le "$step_count" ] || usage
np=$(integer "$GRASP_RUN_NP") || bad_setting GRASP_RUN_NP "$GRASP_RUN_NP" '1–100000'
[ "$np" -ge 1 ] && [ "$np" -le 100000 ] || bad_setting GRASP_RUN_NP "$GRASP_RUN_NP" '1–100000'
GRASP_RUN_NP=$np
export GRASP_RUN_NP
case "$GRASP_RUN_NICE" in 0|1) ;; *) bad_setting GRASP_RUN_NICE "$GRASP_RUN_NICE" '0 or 1' ;; esac
if [ "$GRASP_RUN_NICE" = 1 ] && [ "${_GRASP_RUN_NICED-0}" != 1 ] && command -v nice >/dev/null 2>&1; then
    export _GRASP_RUN_NICED=1
    exec nice -n 10 sh "$script_dir/run.sh" "$@"
fi
if [ -n "$GRASP_RUN_BINDIR" ]; then export PATH="$GRASP_RUN_BINDIR:$PATH"; fi
case "$GRASP_RUN_MPI_TMP" in /*) MPI_TMP="$GRASP_RUN_MPI_TMP" ;; *) MPI_TMP="$PWD/$GRASP_RUN_MPI_TMP" ;; esac
if [ "$GRASP_RUN_NP" -gt 1 ]; then
    [ -n "$GRASP_RUN_MPIRUN" ] || bad_setting GRASP_RUN_MPIRUN '' 'an MPI launcher command'
    mkdir -p "$MPI_TMP"
    export MPI_TMP
    export HWLOC_COMPONENTS="${HWLOC_COMPONENTS:--gl}"
fi
'''

MCP_CHECK = '''grasp_check_mcp() {
    angular=mcp.30
    if [ "$GRASP_RUN_NP" -gt 1 ]; then
        angular="$MPI_TMP/000/mcp000.30"
        ranks=0
        while [ -f "$MPI_TMP/$(printf '%03d' "$ranks")/mcp$(printf '%03d' "$ranks").30" ]; do
            ranks=$((ranks + 1))
        done
        if [ "$ranks" -ne "$GRASP_RUN_NP" ]; then
            echo "Angular data has $ranks MPI ranks, expected $GRASP_RUN_NP. Run rangular again." >&2
            return 1
        fi
    fi
    if [ ! -f "$angular" ]; then
        echo "Missing angular data ($angular). Run rangular first." >&2
        return 1
    fi
    if [ -f rcsf.inp ] && [ rcsf.inp -nt "$angular" ]; then
        echo 'rcsf.inp is newer than the angular data. Run rangular again.' >&2
        return 1
    fi
}
'''

RUN_TRAP = '''step=0
trap '
    rc=$?
    if [ "$rc" -ne 0 ] && [ "$step" -gt 0 ]; then echo "Step $step failed (exit $rc)" >&2; fi
    exit "$rc"
' 0
'''


def _header(revision):
    return [MARKER, f"# Record revision: {revision}"]


def _comment(text):
    return " ".join(text.splitlines()).strip()


def _default(name, value):
    return f"{name}=${{{name}-{shlex.quote(str(value))}}}"


def _wrappers(jobs):
    programs = sorted({job["prog"] for job in jobs if job.get("mpi")})
    check = {job["prog"] for job in jobs if job["prog"] in ("rmcdhf", "rmcdhf_mem")}
    lines = [MCP_CHECK] if check else []
    if programs:
        lines += ['grasp_mpi() { sh -c \'exec \'"$GRASP_RUN_MPIRUN"\' "$@"\' grasp-mpi "$@"; }']
    for program in sorted(set(programs) | check):
        if not re.fullmatch(r"[a-zA-Z_][a-zA-Z_0-9]*", program) or program in RESERVED:
            # 裸命令允许绝对路径；POSIX 函数不能用该路径命名。
            lines += ['if [ "$GRASP_RUN_NP" -gt 1 ]; then',
                      f"    echo {shlex.quote('No portable MPI wrapper for ' + program)} >&2",
                      "    exit 2", "fi"]
            continue
        lines += [f"{program}() {{"]
        if program in check:
            lines += ["    grasp_check_mcp"]
        if program in programs:
            lines += ['    if [ "$GRASP_RUN_NP" -gt 1 ]; then',
                      f'        grasp_mpi {program}_mpi "$@"', "    else",
                      f'        command {program} "$@"', "    fi"]
        else:
            lines += [f'    command {program} "$@"']
        lines += ["}"]
    return lines


def _step_comment(job):
    step, values = summary.page(job)
    reads = step.inputs(values, {"np": 1}) if step is not None else None
    writes = step.outputs(values, {"np": 1}) if step is not None else None
    if reads is None and writes is None:
        return "#    reads/writes: not declared"

    def paths(items):
        return "not declared" if items is None else _comment(", ".join(items)) or "none"

    return f"#    reads: {paths(reads)}   writes: {paths(writes)}"


def run_text(data, revision, settings):
    jobs = data["pipeline"]
    launcher = shlex.join(shlex.split(settings["mpirun"] or "mpirun"))
    launcher += ' -np "$GRASP_RUN_NP"'
    lines = ["#!/bin/sh", *_header(revision), "set -eu",
             'script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)', 'cd "$script_dir/.."',
             "if [ ! -f .grasp_gui.json ]; then",
             "    echo 'Missing .grasp_gui.json in the calculation directory.' >&2", "    exit 2", "fi", "",
             "# GRASP bin on the machine that generated this script; override with the environment.",
             _default("GRASP_RUN_BINDIR", settings["bindir"]),
             _default("GRASP_RUN_NP", settings["np"]), _default("GRASP_RUN_MPIRUN", launcher),
             _default("GRASP_RUN_MPI_TMP", settings["mpitmp"] or "tmp_mpi"),
             _default("GRASP_RUN_NICE", int(bool(settings["nice"]))), "",
             f"step_count={len(jobs)}",
             'usage() { echo "Usage: sh grasp_run/run.sh [start end], 1 <= start <= end <= $step_count" >&2; exit 2; }',
             RUN_SETUP, *core.program_fallbacks(jobs), *_wrappers(jobs), RUN_TRAP]
    for number, job in enumerate(jobs, 1):
        lines += [f"# {number}. {_comment(job['title'])}", _step_comment(job),
                  f'if [ "$start" -le {number} ] && [ "$end" -ge {number} ]; then', f"step={number}",
                  core.describe(job, fallback=False), "fi", ""]
    lines += ["step=0", 'echo "Completed steps ${start}–${end}"', ""]
    return "\n".join(lines)


def _slurm_mpi(value):
    # 现有 Slurm 启动前缀可以用变量。固定计数需要和提交时的实际计数核对。
    value = re.sub(r"\$\{SLURM_NTASKS\}|\$SLURM_NTASKS(?![A-Za-z0-9_])", "${GRASP_RUN_NP}", value)
    fixed = re.findall(r"(?:^|\s)(?:-np|-n|--ntasks)(?:=|\s+)([0-9]+)(?=\s|$)", value)
    return value, fixed


def _slurm_tmp(value):
    # 本机已有的 Slurm 路径变量可以展开，除此之外的路径字符按字面使用。
    for variable in ("SLURM_SUBMIT_DIR", "HOME"):
        value = re.sub(r"\$\{" + variable + r"\}|\$" + variable + r"(?![A-Za-z0-9_])",
                       lambda m: "\x00" + variable + "\x00", value)
    if value.startswith("~/"):
        value = "\x00HOME\x00/" + value[2:]
    parts = value.split("\x00")
    return "".join(f'"${{{part}}}"' if i % 2 else shlex.quote(part) if part else ""
                   for i, part in enumerate(parts))


def submit_text(data, revision):
    stored = data.get("slurm", {})
    slurm = {key: str(stored.get(key, value)).strip() for key, value in core.SLURM_DEFAULTS.items()}
    nodes = slurm["nodes"] or "1"
    tasks = slurm["ntasks"] or "1"
    fallback = int(nodes) * int(tasks)
    launcher, fixed = _slurm_mpi(slurm["mpirun"])
    shell, *directives = core.slurm_directives(slurm)
    lines = [shell, *_header(revision), *directives, "", "set -e",
             'if [ -z "${SLURM_SUBMIT_DIR-}" ] || ! cd "$SLURM_SUBMIT_DIR"; then',
             "    echo 'Submit from the calculation directory using sbatch grasp_run/submit.sbatch.' >&2",
             "    exit 2", "fi",
             "if [ ! -f .grasp_gui.json ] || [ ! -f grasp_run/run.sh ]; then",
             "    echo 'The submission directory must contain .grasp_gui.json and grasp_run/run.sh.' >&2",
             "    exit 2", "fi", ""]
    modules = core.nonblank_lines(slurm["modules"])
    if modules:
        lines += [*modules, ""]
    lines += ["# GRASP bin from the Slurm settings. Override with the environment.",
              f'GRASP_RUN_BINDIR=${{GRASP_RUN_BINDIR-{path_expression(slurm["bindir"])}}}']
    if launcher:
        lines += [f'GRASP_RUN_NP=${{GRASP_RUN_NP-${{SLURM_NTASKS:-{fallback}}}}}']
    else:
        lines += [_default("GRASP_RUN_NP", 1)]
    for count in sorted(set(fixed)):
        lines += [f'if [ "${{GRASP_RUN_MPIRUN+x}}" != x ] && [ "$GRASP_RUN_NP" != {int(count)} ]; then',
                  f'    echo "MPI launcher fixes the process count at {count} but GRASP_RUN_NP is $GRASP_RUN_NP." >&2',
                  "    echo 'Use GRASP_RUN_NP in the launcher prefix.' >&2", "    exit 2", "fi"]
    lines += [_default("GRASP_RUN_MPIRUN", launcher),
              f'GRASP_RUN_MPI_TMP=${{GRASP_RUN_MPI_TMP-{_slurm_tmp(slurm["mpitmp"] or "$SLURM_SUBMIT_DIR/tmp_mpi")}}}',
              _default("GRASP_RUN_NICE", 0),
              "export GRASP_RUN_BINDIR GRASP_RUN_NP GRASP_RUN_MPIRUN GRASP_RUN_MPI_TMP GRASP_RUN_NICE",
              'exec sh grasp_run/run.sh "$@"', ""]
    return "\n".join(lines)


def _existing(fd, name):
    try:
        opened = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
    except FileNotFoundError:
        return None
    with os.fdopen(opened, "rb") as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode):
            raise ValueError(T("脚本路径不是普通文件：{name}", name=name))
        header = b"".join(stream.readline(128) for _ in range(3))
        return (header + stream.read() if _ours(header) else header), info


def _ours(raw):
    # 标记位于固定文件头，避免用户文件正文中碰巧出现的文字成为覆盖授权。
    header = raw.split(b"\n", 3)
    return (len(header) >= 3 and header[0] in (b"#!/bin/sh", b"#!/bin/bash") and header[1] == MARKER.encode()
            and re.fullmatch(rb"# Record revision: [0-9a-f]{64}", header[2]) is not None)


def _check_unchanged(fd, name, previous):
    now = os.stat(name, dir_fd=fd, follow_symlinks=False)
    if (now.st_dev, now.st_ino, now.st_ctime_ns) != (previous.st_dev, previous.st_ino, previous.st_ctime_ns):
        raise ValueError(T("脚本在重建期间被修改：{name}", name=name))


def _replace(fd, name, raw, existing):
    temp = ".grasp-script-" + uuid.uuid4().hex
    opened = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o700, dir_fd=fd)
    try:
        with os.fdopen(opened, "wb") as stream:
            stream.write(raw)
        if existing is None:
            os.link(temp, name, src_dir_fd=fd, dst_dir_fd=fd, follow_symlinks=False)
        else:
            _check_unchanged(fd, name, existing)
            os.replace(temp, name, src_dir_fd=fd, dst_dir_fd=fd)
            return
    except BaseException:
        os.unlink(temp, dir_fd=fd)
        raise
    os.unlink(temp, dir_fd=fd)


def rebuild(workdir, data, revision, *, bindir=None, defaults=None):
    """调用方持有目录锁；收集每个脚本的警告，保存记录的结果保持有效。"""
    warnings, paths = [], []
    workdir = Path(workdir)
    active = bool(data.get("pipeline"))

    def warn(name, error):
        warnings.append(T("重建 {name} 失败：{e}", name=f"{DIRECTORY}/{name}" if name else DIRECTORY, e=str(error)))

    try:
        root = os.open(workdir, DIR_FLAGS)
    except OSError as e:
        warn("", e)
        return paths, warnings
    try:
        if active:
            try:
                os.mkdir(DIRECTORY, 0o755, dir_fd=root)
            except FileExistsError:
                pass
        try:
            fd = os.open(DIRECTORY, DIR_FLAGS, dir_fd=root)
        except FileNotFoundError:
            if active:
                raise
            return paths, warnings
        try:
            for name in SCRIPTS:
                try:
                    existing = _existing(fd, name)
                    if existing is not None and not _ours(existing[0]):
                        if active:
                            raise ValueError(T("同名脚本由用户管理，已保留"))
                        continue
                    if not active:
                        if existing is not None:
                            _check_unchanged(fd, name, existing[1])
                            os.unlink(name, dir_fd=fd)
                        continue
                    if name == "run.sh":
                        if defaults is None:
                            defaults = core.saved_run_settings(persist=False)
                        settings = dict(defaults, **{key: data[key] for key in ("np", "mpirun", "mpitmp", "nice")
                                                     if key in data})
                        if bindir is not None:
                            settings["bindir"] = bindir
                        text = run_text(data, revision, settings)
                    else:
                        text = submit_text(data, revision)
                    raw = text.encode("utf-8")
                    if existing is None or existing[0] != raw:
                        _replace(fd, name, raw, existing[1] if existing else None)
                    paths.append(str(workdir / DIRECTORY / name))
                except (OSError, ValueError, TypeError, KeyError, AttributeError) as e:
                    warn(name, e)
        finally:
            os.close(fd)
        if not active:
            try:
                os.rmdir(DIRECTORY, dir_fd=root)
            except OSError as e:
                if e.errno != errno.ENOTEMPTY:
                    warn("", e)
    except OSError as e:
        warn("", e)
    finally:
        os.close(root)
    return paths, warnings
