def stdin_of(job):
    step = STEPS[job["step"]]
    return step.stdin({f.key: core.normalize(f, job["vals"][f.key]) for f in step.fields
                       if isinstance(f, core.Field)})


def norm(text):
    return [ln.strip() for ln in text.strip().splitlines()]


def find(roots, d, name):
    for root in roots:
        path = os.path.join(root, d.src, name)
        if os.path.exists(path):
            return path
    return None


def check(d, roots):
    """Compare the generated input with the manual's input files; return the number of differences."""
    bad = same = equivalent = 0
    for i, src in d.checks:
        if not src:
            continue
        filename = src[0] if isinstance(src, tuple) else src
        with open(find(roots, d, filename)) as f:
            want = f.read()
        if isinstance(src, tuple):
            # 序列脚本读取指定的 heredoc；只替换明确给定的变量，不执行 shell。
            _, marker, occurrence, variables = src
            pattern = r"<<\s*" + re.escape(marker) + r"[ \t]*\n(.*?)\n" + re.escape(marker) + r"[ \t]*(?:\n|$)"
            want = re.findall(pattern, want, re.S)[occurrence]
            want = re.sub(r"\$\{(\w+)\}|\$(\w+)",
                          lambda m: variables[m[1] or m[2]], want)
        got = stdin_of(d.jobs[i])
        actual, expected = norm(got), norm(want)
        reason = d.equivalent(d.jobs[i], actual, expected) if d.equivalent else ""
        if actual == expected:
            same += 1
        elif reason:
            equivalent += 1
            print(f"  {d.id} job {i + 1}: equivalent ({reason})")
        else:
            bad += 1
            print(f"  {d.id} job {i + 1} ({d.jobs[i]['step']}) differs from {src}:\n"
                  f"    manual: {norm(want)}\n    demo:   {norm(got)}")
    print(f"  {d.id}: {same} identical, {equivalent} equivalent, {bad} differences")
    return bad


def reference(d, roots):
    out = []
    for name in d.refs:
        path = find(roots, d, name)
        if not path:
            print(f"  {d.id}: no reference result {name}")
            continue
        blocks = grasp_mix.read_mix(path)
        out.append(dict(file=os.path.basename(name), energies=[round(lv.energy, 10) for b in blocks for lv in b.levels]))
    return out


