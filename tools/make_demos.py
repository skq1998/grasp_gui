    d.cp(f"{n3}.w", f"{n3}.bw")
    d.cp(f"{n3}.cm", f"{n3}.cbm")
    d.add("rtransition", "rtransition_input", ci=True, init=n3, final=n3, kind="M1", m1_diffj=False,
          log="out_transition")
    return d


